#!/usr/bin/env python
"""Train script for the Team Partition benchmark (SDec-MAT and MAT-Dec).

Derived from `train_charging.py`. Differences worth knowing:

  * Every constructor argument of the paper configuration (mac/presets.py) is
    exposed as a CLI override of the same name, defaulting to the paper value.
    Override values are parsed as YAML scalars, so `--gate_deadline null`,
    `--commit_gate false`, `--public_regrouped count` and
    `--fixed_quota "[2, 2, 2]"` all work. Keep `--episode_length` equal to
    `--time_limit` (20).
  * `--comm_mask_kind bits` is REQUIRED for mat_comm / mat_comm_gru (it is
    config.py's default). `get_comm_mask()` is (N, 1) per-agent bits and the
    wrapper appends them to share_obs. `assert_comm_mask_kind` refuses a wrong
    reading.
  * `--algorithm_name mat_dec` gives the decentralised MAT-Dec arm (shared
    per-agent MLP actor, no comm), exactly as in every other train script.
  * Episodes end early (the first resolving GO, or the gate deadline / commit
    window expiring), so rollouts do not align with episode boundaries. The vec
    env auto-resets and the GRU state is zeroed on done, so that is harmless.

The paper's commands are generated by `run_experiment.py` at the repo root.

Run directory layout: mat/scripts/results/<env>/<scenario>/<algo>/<exp>/runN,
with the resolved env kwargs saved next to the logs as env_kwargs.json.
"""

import json
import os
import socket
import sys
from pathlib import Path

import numpy as np
import setproctitle
import torch
import wandb
import yaml

# <repo>/Multi-Agent-Transformer_ctsde/mat/scripts/train/this_file.py -> the dir
# that holds the `mat` package, so `import mat.…` works from anywhere.
sys.path.append(str(Path(os.path.abspath(__file__)).parents[3]))

from mat.config import get_config
from mat.envs.team_partition.team_partition_mat_wrapper import (
    TeamPartitionMATWrapper,
    assert_comm_mask_kind,
    env_arg_defaults,
    num_agents_from,
)
from mat.envs.env_wrappers import ShareSubprocVecEnv, ShareDummyVecEnv
from mat.runner.shared.team_partition_runner import TeamPartitionRunner as Runner

ENV_NAME = "TeamPartition"


def make_train_env(all_args):
    def get_env_fn(rank):
        def init_env():
            if all_args.env_name != ENV_NAME:
                raise NotImplementedError(
                    "Can not support the " + all_args.env_name + " environment.")
            env = TeamPartitionMATWrapper(all_args)
            env.seed(all_args.seed + rank * 1000)
            return env

        return init_env

    if all_args.n_rollout_threads == 1:
        return ShareDummyVecEnv([get_env_fn(0)])
    return ShareSubprocVecEnv([get_env_fn(i) for i in range(all_args.n_rollout_threads)])


def make_eval_env(all_args):
    def get_env_fn(rank):
        def init_env():
            if all_args.env_name != ENV_NAME:
                raise NotImplementedError(
                    "Can not support the " + all_args.env_name + " environment.")
            env = TeamPartitionMATWrapper(all_args)
            # Disjoint from the training seeds so eval episodes are unseen.
            env.seed(all_args.seed * 50000 + rank * 10000)
            return env

        return init_env

    if all_args.n_eval_rollout_threads == 1:
        return ShareDummyVecEnv([get_env_fn(0)])
    return ShareSubprocVecEnv([get_env_fn(i) for i in range(all_args.n_eval_rollout_threads)])


def parse_args(args, parser):
    parser.add_argument('--scenario_name', type=str, default='team_partition',
                        help="Name used for the results directory")
    parser.add_argument('--run_dir', type=str, default='')

    # One override flag per env constructor argument of the paper preset. A
    # name that already means something to MAT would be read by both, so
    # refuse it.
    defaults = env_arg_defaults()
    taken = {a.dest for a in parser._actions}
    clash = sorted(set(defaults) & taken)
    if clash:
        raise ValueError(
            f"Team Partition env args {clash} collide with existing MAT config "
            "flags; the value would be fed to both.")
    for key, value in defaults.items():
        parser.add_argument(f'--{key}', type=yaml.safe_load, default=value,
                            metavar="VALUE",
                            help=f"env arg (paper: {value!r})")

    all_args = parser.parse_known_args(args)[0]
    return all_args


def main(args):
    parser = get_config()
    all_args = parse_args(args, parser)

    if all_args.algorithm_name == "mat_dec":
        all_args.dec_actor = True
        all_args.share_actor = True

    if all_args.encode_state:
        # Unsafe for every algorithm here, for two different reasons:
        #   mat/mat_dec/...: ma_transformer.py replaces the state with
        #     np.zeros(..., 37), so the encoder would see only zeros.
        #   mat_comm: share_obs is one global state tiled per agent, so encoding
        #     it hands every agent every distance and the quota -- voiding the
        #     communication masking (enforced again in the model constructor).
        raise ValueError(
            "--encode_state is unsafe in this setup. For {} the encoder must "
            "run on per-agent observations.".format(all_args.algorithm_name))

    assert_comm_mask_kind(all_args)

    # Build one env up front: fails fast on a bad override (rather than inside
    # 32 subprocesses), and gives the banner the resolved kwargs and horizon.
    probe = TeamPartitionMATWrapper(all_args)
    all_args.env_kwargs = dict(probe.env_kwargs)
    all_args.env_horizon = int(probe.episode_limit)
    probe.close()

    if all_args.episode_length != all_args.env_horizon:
        print("[warn] episode_length ({}) != env horizon ({}); a rollout then spans a "
              "different number of steps than one full-length episode."
              .format(all_args.episode_length, all_args.env_horizon))
    if all_args.obs_agent_id:
        print("[note] --obs_agent_id true: agents get a one-hot id (the paper's "
              "Team Partition protocol).")

    # cuda
    if all_args.cuda and torch.cuda.is_available():
        print("choose to use gpu...")
        device = torch.device("cuda:0")
        torch.set_num_threads(all_args.n_training_threads)
        if all_args.cuda_deterministic:
            torch.backends.cudnn.benchmark = False
            torch.backends.cudnn.deterministic = True
    else:
        print("choose to use cpu...")
        device = torch.device("cpu")
        torch.set_num_threads(all_args.n_training_threads)

    run_dir = Path(os.path.split(os.path.dirname(os.path.abspath(__file__)))[0] + "/results") \
        / all_args.env_name / all_args.scenario_name / all_args.algorithm_name / all_args.experiment_name
    if not run_dir.exists():
        os.makedirs(str(run_dir))

    if all_args.use_wandb:
        run = wandb.init(config=all_args,
                         project=all_args.env_name,
                         entity=all_args.user_name,
                         notes=socket.gethostname(),
                         name=str(all_args.algorithm_name) + "_" +
                              str(all_args.experiment_name) +
                              "_seed" + str(all_args.seed),
                         group=all_args.scenario_name,
                         dir=str(run_dir),
                         job_type="training",
                         reinit=True)
    else:
        exst_run_nums = [int(str(folder.name).split('run')[1]) for folder in run_dir.iterdir()
                         if str(folder.name).startswith('run')]
        curr_run = 'run1' if len(exst_run_nums) == 0 else 'run%i' % (max(exst_run_nums) + 1)
        run_dir = run_dir / curr_run
        if not run_dir.exists():
            os.makedirs(str(run_dir))

    # The exact game this run played.
    with open(run_dir / "env_kwargs.json", "w") as f:
        json.dump({"horizon": all_args.env_horizon,
                   "obs_agent_id": bool(all_args.obs_agent_id),
                   "env_kwargs": all_args.env_kwargs}, f, indent=2)

    setproctitle.setproctitle(
        str(all_args.algorithm_name) + "-" + str(all_args.env_name) + "-" +
        str(all_args.experiment_name) + "@" + str(all_args.user_name))

    # seed
    torch.manual_seed(all_args.seed)
    torch.cuda.manual_seed_all(all_args.seed)
    np.random.seed(all_args.seed)

    # env
    num_agents = num_agents_from(all_args)
    all_args.run_dir = run_dir
    envs = make_train_env(all_args)
    eval_envs = make_eval_env(all_args) if all_args.use_eval else None

    config = {
        "all_args": all_args,
        "envs": envs,
        "eval_envs": eval_envs,
        "num_agents": num_agents,
        "device": device,
        "run_dir": run_dir
    }

    runner = Runner(config)
    runner.run()

    # post process
    envs.close()
    if all_args.use_eval and eval_envs is not envs:
        eval_envs.close()

    if all_args.use_wandb:
        run.finish()
    else:
        runner.writter.export_scalars_to_json(str(runner.log_dir + '/summary.json'))
        runner.writter.close()


if __name__ == "__main__":
    main(sys.argv[1:])
